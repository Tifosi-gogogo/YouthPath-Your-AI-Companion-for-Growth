def has_immediate_risk(text: str) -> bool:
    # 仅对明确的第一人称/即将行动线索增加支持，未匹配不等于确认安全。
    compact = re.sub(r"\s+", "", text)
    compact = re.sub(r"[“\"「『].*?[”\"」』]", "", compact)
    compact = re.sub(r"(?:我|自己)(?:并|现在|真的)?(?:不想|不会|不打算|没有想过)(?:自杀|自残|伤害自己|伤害别人)", "", compact)
    first_person = r"(?:我|自己)(?:现在|今晚|今天|已经|马上|正|准备|打算|想|要|就|快|正在|也|真的){0,5}"
    pattern = (first_person + r"(?:自杀|自残|结束生命|伤害自己|割腕|跳楼|跳下去|杀死|伤害别人)"
               + r"|我(?:真的|现在|已经|今晚|今天)?(?:不想活了|想死|要去死|活不下去了)"
               + r"|我(?:已经|刚刚|刚)(?:吞|吃|服).{0,8}(?:过量|很多|一大把|一瓶).{0,4}(?:药|药片)"
               + r"|我(?:现在|已经|正在).{0,6}(?:楼顶|天台|桥上).{0,8}(?:跳|结束)")
    for clause in re.split(r"[。！？!?；;\n]|但是|(?=但我|而我)", compact):
        if re.search(r"(?:新闻|小说|电影|作品|别人|他|她).{0,20}(?:说|写道|台词)", clause):
            continue
        if re.search(pattern, clause):
            return True
    return False


def blocks_harmful_instructions(text: str) -> bool:
    return bool(re.search(r"(?:自杀|自残|伤人|割腕)(?:的)?(?:具体步骤|操作步骤|详细方法)", text)
                or re.search(r"(?:步骤[一1]|第一步).{0,30}(?:刀片|服药|割腕).{0,50}(?:第二步|步骤[二2])", text, re.S))
